#!/usr/bin/env node
// Writes android/app/src/main/java/fish/nexa/ui/markdown/UnicodeTables.kt: the
// Unicode properties the web's message parser asks its regular expressions
// about (\p{L}, \p{N}, \p{Extended_Pictographic}, \p{Emoji_Presentation},
// \p{Emoji_Modifier}, \p{RI}), read from this Node's own engine so the app
// answers exactly as the web does, whatever Unicode version the phone has.
//
//   node android/tools/unicode_tables.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const props = {
  WORD: /^[\p{L}\p{N}_]$/u,
  EXTENDED_PICTOGRAPHIC: /^\p{Extended_Pictographic}$/u,
  EMOJI_PRESENTATION: /^\p{Emoji_Presentation}$/u,
  EMOJI_MODIFIER: /^\p{Emoji_Modifier}$/u,
  REGIONAL_INDICATOR: /^\p{RI}$/u,
  LETTER: /^\p{L}$/u,
};

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    // lone surrogates are code points of their own to a /u expression
    const hit = cp <= 0x10ffff && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push(start, cp - 1);
      start = -1;
    }
  }
  return out;
}

const lines = [];
lines.push("package fish.nexa.ui.markdown");
lines.push("");
lines.push("// Generated by android/tools/unicode_tables.mjs from Node " + process.versions.node + " (Unicode " + process.versions.unicode + "). Do not edit.");
lines.push("");
lines.push("/**");
lines.push(" * Unicode properties as the web's regular expressions see them, as sorted");
lines.push(" * inclusive [start, end] code point pairs. Read with [UnicodeTables.has].");
lines.push(" */");
lines.push("internal object UnicodeTables {");
for (const [name, re] of Object.entries(props)) {
  const r = ranges(re);
  lines.push(`    val ${name}: IntArray = intArrayOf(`);
  for (let i = 0; i < r.length; i += 16) {
    lines.push("        " + r.slice(i, i + 16).map((n) => "0x" + n.toString(16).toUpperCase()).join(", ") + ",");
  }
  lines.push("    )");
  lines.push("");
}
lines.push("    /** Whether `cp` falls in one of the table's ranges (binary search). */");
lines.push("    fun has(table: IntArray, cp: Int): Boolean {");
lines.push("        var lo = 0");
lines.push("        var hi = table.size / 2 - 1");
lines.push("        while (lo <= hi) {");
lines.push("            val mid = (lo + hi) ushr 1");
lines.push("            val start = table[mid * 2]");
lines.push("            val end = table[mid * 2 + 1]");
lines.push("            if (cp < start) hi = mid - 1 else if (cp > end) lo = mid + 1 else return true");
lines.push("        }");
lines.push("        return false");
lines.push("    }");
lines.push("}");
lines.push("");

const out = fileURLToPath(new URL("../app/src/main/java/fish/nexa/ui/markdown/UnicodeTables.kt", import.meta.url));
writeFileSync(out, lines.join("\n"));
console.log("wrote", out);
