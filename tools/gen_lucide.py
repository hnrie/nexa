#!/usr/bin/env python3
"""Turns the lucide icon set into Compose ImageVectors, so the phone draws the
same icons the browser does."""
import json, math, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from lucide_map import MAP

SRC = Path("/path/to/nexa/web/node_modules/lucide-react/dist/esm/icons")
OUT = Path("/path/to/nexa/android/app/src/main/java/xyz/evilion/chat/ui/icons/Lucide.kt")


def read_icon(name):
    f = SRC / f"{name}.mjs"
    if not f.exists():
        return None
    text = f.read_text()
    # some names are aliases that simply re-export another icon
    alias = re.search(r"export \{ default \} from '\./([\w-]+)\.mjs';", text)
    if alias:
        return read_icon(alias.group(1))
    at = text.find("node:")
    if at < 0:
        return None
    start = text.index("[", at)
    depth, i, in_str = 0, start, False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 2
                continue
            if c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                break
        i += 1
    raw = text[start:i + 1]
    raw = re.sub(r'([\[{,]\s*)([A-Za-z_][\w-]*)\s*:', r'\1"\2":', raw)
    raw = re.sub(r",(\s*[\]\}])", r"\1", raw)
    return json.loads(raw)


def arc(cx, cy, r):
    """A circle as two arc commands, which every path parser understands."""
    return f"M{cx - r} {cy}A{r} {r} 0 1 0 {cx + r} {cy}A{r} {r} 0 1 0 {cx - r} {cy}"


def to_path(node):
    tag, attrs = node[0], node[1]
    f = lambda k, d=0: float(attrs.get(k, d))
    if tag == "path":
        return attrs["d"]
    if tag == "circle":
        return arc(f("cx"), f("cy"), f("r"))
    if tag == "ellipse":
        cx, cy, rx, ry = f("cx"), f("cy"), f("rx"), f("ry")
        return f"M{cx - rx} {cy}A{rx} {ry} 0 1 0 {cx + rx} {cy}A{rx} {ry} 0 1 0 {cx - rx} {cy}"
    if tag == "line":
        return f'M{f("x1")} {f("y1")}L{f("x2")} {f("y2")}'
    if tag == "rect":
        x, y, w, h = f("x"), f("y"), f("width"), f("height")
        rx = f("rx", 0) or f("ry", 0)
        if rx <= 0:
            return f"M{x} {y}h{w}v{h}h{-w}z"
        return (f"M{x + rx} {y}h{w - 2 * rx}a{rx} {rx} 0 0 1 {rx} {rx}"
                f"v{h - 2 * rx}a{rx} {rx} 0 0 1 {-rx} {rx}"
                f"h{-(w - 2 * rx)}a{rx} {rx} 0 0 1 {-rx} {-rx}"
                f"v{-(h - 2 * rx)}a{rx} {rx} 0 0 1 {rx} {-rx}z")
    if tag in ("polyline", "polygon"):
        pts = re.findall(r"-?[\d.]+", attrs.get("points", ""))
        if len(pts) < 4:
            return ""
        d = "M" + pts[0] + " " + pts[1] + "".join(f"L{pts[i]} {pts[i+1]}" for i in range(2, len(pts) - 1, 2))
        return d + ("z" if tag == "polygon" else "")
    return ""


def main():
    names = sorted(set(MAP.values()))
    icons = {}
    missing = []
    for n in names:
        data = read_icon(n)
        if not data:
            missing.append(n)
            continue
        paths = [p for p in (to_path(node) for node in data) if p]
        if paths:
            icons[n] = paths
    if missing:
        print("no such lucide icon:", missing, file=sys.stderr)

    def kt_name(n):
        return "".join(part.capitalize() if not part.isdigit() else part for part in n.split("-"))

    lines = [
        "package xyz.evilion.chat.ui.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.PathParser",
        "import androidx.compose.ui.unit.dp",
        "",
        "/**",
        " * The icon set the web client uses (lucide), as Compose vectors, generated",
        " * from the same artwork the browser loads. The two apps were drawing",
        " * different pictures for the same things; now a button means the same thing",
        " * whichever one someone opens.",
        " *",
        " * Every icon is a 24-unit box, stroked at 2 with round caps and joins, and",
        " * takes its colour from wherever it is drawn, exactly as lucide's own SVGs do.",
        " *",
        " * Generated by tools/gen_lucide.py from web/node_modules/lucide-react; do not",
        " * edit by hand.",
        " */",
        "object Lucide {",
        "    private fun icon(vararg paths: String): ImageVector {",
        "        val builder = ImageVector.Builder(",
        "            defaultWidth = 24.dp,",
        "            defaultHeight = 24.dp,",
        "            viewportWidth = 24f,",
        "            viewportHeight = 24f,",
        "        )",
        "        for (d in paths) {",
        "            builder.addPath(",
        "                pathData = PathParser().parsePathString(d).toNodes(),",
        "                fill = null,",
        "                stroke = SolidColor(Color.Black),",
        "                strokeLineWidth = 2f,",
        "                strokeLineCap = StrokeCap.Round,",
        "                strokeLineJoin = StrokeJoin.Round,",
        "            )",
        "        }",
        "        return builder.build()",
        "    }",
        "",
    ]
    for n in sorted(icons):
        args = ", ".join(json.dumps(p) for p in icons[n])
        lines.append(f"    val {kt_name(n)}: ImageVector by lazy {{ icon({args}) }}")
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(icons)} icons to {OUT}")


main()
